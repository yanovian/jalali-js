import type { CalendarDateFields, CalendarEngine } from './calendar-engine.js';

const DAYS_IN_MONTH = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

function isLeapYear(year: number): boolean {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
}

function daysInMonth(year: number, month: number): number {
  if (month === 2 && isLeapYear(year)) return 29;
  return DAYS_IN_MONTH[month - 1] as number;
}

// The standard Fliegel & Van Flandern algorithm for the proleptic Gregorian calendar. Uses
// astronomical year numbering (year 0 exists, and precedes year 1), matching ISO 8601.
function toJulianDayNumber({ year, month, day }: CalendarDateFields): number {
  const a = Math.floor((14 - month) / 12);
  const y = year + 4800 - a;
  const m = month + 12 * a - 3;
  return (
    day +
    Math.floor((153 * m + 2) / 5) +
    365 * y +
    Math.floor(y / 4) -
    Math.floor(y / 100) +
    Math.floor(y / 400) -
    32045
  );
}

// The inverse of toJulianDayNumber above.
function fromJulianDayNumber(jdn: number): CalendarDateFields {
  const a = jdn + 32044;
  const b = Math.floor((4 * a + 3) / 146097);
  const c = a - Math.floor((146097 * b) / 4);
  const d = Math.floor((4 * c + 3) / 1461);
  const e = c - Math.floor((1461 * d) / 4);
  const m = Math.floor((5 * e + 2) / 153);
  const day = e - Math.floor((153 * m + 2) / 5) + 1;
  const month = m + 3 - 12 * Math.floor(m / 10);
  const year = 100 * b + d - 4800 + Math.floor(m / 10);
  return { year, month, day };
}

export const gregorianEngine: CalendarEngine = {
  system: 'gregorian',
  monthsInYear: 12,
  isLeapYear,
  daysInMonth,
  toJulianDayNumber,
  fromJulianDayNumber,
};
